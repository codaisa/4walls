def mirror(p):
    return (-p[0], p[1], p[2])


def build_base(mats):
    """Body, boots, fists and the soft block head shared by every character."""
    parts = {}  # bone name -> list of rigid objects
    # Body skeleton for the Skin modifier.
    names = ["pelvis", "chest", "neck", "hipL", "kneeL", "ankleL", "hipR", "kneeR", "ankleR", "shoulderL", "elbowL", "wristL", "shoulderR", "elbowR", "wristR"]
    pos = {**J, **{k.replace("L", "R"): mirror(v) for k, v in J.items() if k.endswith("L")}}
    verts = [pos[n] for n in names]
    idx = {n: i for i, n in enumerate(names)}
    e = lambda a, b: (idx[a], idx[b])
    edges = [
        e("pelvis", "chest"), e("chest", "neck"),
        e("pelvis", "hipL"), e("hipL", "kneeL"), e("kneeL", "ankleL"),
        e("pelvis", "hipR"), e("hipR", "kneeR"), e("kneeR", "ankleR"),
        e("chest", "shoulderL"), e("shoulderL", "elbowL"), e("elbowL", "wristL"),
        e("chest", "shoulderR"), e("shoulderR", "elbowR"), e("elbowR", "wristR"),
    ]
    radius = {"pelvis": 0.165, "chest": 0.165, "neck": 0.11, "hip": 0.085, "knee": 0.075, "ankle": 0.07, "shoulder": 0.082, "elbow": 0.072, "wrist": 0.066}
    radii = []
    for n in names:
        key = n.rstrip("LR") if n not in ("pelvis", "chest", "neck") else n
        r = radius[key]
        radii.append((r, r * 0.95))
    body = skin_body("Body", verts, edges, radii, idx["pelvis"], mats["Suit"])

    # Thick black belt + yellow buckle with a dark slot.
    parts.setdefault("hips", []).append(torus("Belt", 0.152, 0.024, (0, 0, 0.265), mats["Dark"], scale=(1, 0.95, 2.1)))
    buckle = rounded_box("Buckle", (0.06, 0.012, 0.042), (0, -0.172, 0.265), mats["Gold"], bevel=0.012, subdiv=1)
    hole = rounded_box("BuckleHole", (0.032, 0.006, 0.016), (0, -0.182, 0.265), mats["Dark"], bevel=0.006, subdiv=1)
    parts["hips"].extend([buckle, hole])

    # Big rounded boots.
    for side, s in (("L", 1), ("R", -1)):
        boot = uv_sphere(f"Boot{side}", 0.1, (0.1 * s, -0.035, 0.068), scale=(1.05, 1.38, 0.78), mat=mats["Boot"])
        parts.setdefault(f"foot.{side}", []).append(boot)

    # Big ball fists with a thumb bump.
    for side, s in (("L", 1), ("R", -1)):
        fist = uv_sphere(f"Glove{side}", 0.098, (0.315 * s, -0.03, 0.27), scale=(1, 1, 0.95), mat=mats["Glove"])
        thumb = uv_sphere(f"Thumb{side}", 0.036, (0.285 * s, -0.1, 0.3), mat=mats["Glove"])
        parts.setdefault(f"hand.{side}", []).extend([fist, thumb])

    # Head: a big soft block (slightly narrower at the chin) with tall glossy pill eyes.
    # Expression eyes (happy arcs, defeated X) share the face; the game shows one set at a time.
    hz = HEAD_Z
    head_obj = rounded_box("Head", HEAD_HALF, (0, 0, hz), mats["Head"], bevel=HEAD_BEVEL, taper=HEAD_TAPER)
    head = [head_obj]
    ez = hz - 0.015
    for side, s in (("L", 1), ("R", -1)):
        x = 0.112 * s
        head.append(face_decal(f"Eye{side}", head_obj, mats["Eye"], x, ez, 0.1, 0.26, n=3.2))
        head.append(face_decal(f"EyeHappy{side}", head_obj, mats["EyeHappy"], x, ez - 0.01, 0.13, 0.036, n=2.2, bend=9.0))
        for i, a in enumerate((math.pi / 4, -math.pi / 4)):
            head.append(face_decal(f"EyeX{side}{i}", head_obj, mats["EyeX"], x, ez, 0.03, 0.16, n=2.2, angle=a))
    parts["head"] = head
    return body, parts


def ninja_gear(mats, parts):
    hz = HEAD_Z
    hw, hd, hh = HEAD_HALF
    # Headband hugging the block head above the eyes, knot and two tails at the back.
    band_z = 0.17
    parts["head"].append(shell_slice("Headband", (hw + 0.012, hd + 0.012, hh + 0.012), (0, 0, hz), mats["Cloth"], lambda c: abs(c.z - band_z) < 0.04, thickness=0.014, bevel=HEAD_BEVEL, taper=HEAD_TAPER))
    parts["head"].append(uv_sphere("Knot", 0.04, (0, hd + 0.03, hz + band_z), mat=mats["Cloth"]))
