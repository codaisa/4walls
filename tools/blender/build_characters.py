def build_character(char_id):
    reset_scene()
    mats = make_materials()
    body, parts = build_base(mats)
    if char_id == "ninja":
        ninja_gear(mats, parts)
    elif char_id == "engenheiro":
        engineer_gear(mats, parts)
    elif char_id in hero_gear.GEAR:
        hero_gear.setup(sys.modules[__name__])
        hero_gear.GEAR[char_id](mats, parts)
    rig = build_rig(char_id)
    mesh = skin_to_rig(rig, body, parts)
    mesh.name = char_id
    actions = build_actions(rig)
    # Chibi-tuned locomotion/action clips, then Mixamo mocap where it suits the body (Idle, Defeat).
    build_chibi_actions(rig, new_action)
    apply_mixamo(rig, MIXAMO_DIR)
    return rig, mesh, actions


def export(char_id, rig, mesh):
    os.makedirs(OUT_DIR, exist_ok=True)
    path = os.path.join(OUT_DIR, f"{char_id}.glb")
    bpy.ops.object.select_all(action="DESELECT")
    rig.select_set(True)
    mesh.select_set(True)
    bpy.ops.export_scene.gltf(
        filepath=path,
        export_format="GLB",
        use_selection=True,
        export_yup=True,
        export_apply=True,
        export_animations=True,
        export_animation_mode="ACTIONS",
        export_force_sampling=True,
        export_optimize_animation_size=True,
        export_skins=True,
        export_all_influences=False,
        export_materials="EXPORT",
    )
    print(f"[4walls] exported {path} ({os.path.getsize(path) // 1024} KB)")


def preview(char_id, rig, action_name, frame, suffix, eyes="Eye", view="front"):
    if not PREVIEW_DIR:
        return
    os.makedirs(PREVIEW_DIR, exist_ok=True)
    scene = bpy.context.scene
    rig.animation_data.action = bpy.data.actions[action_name]
    for name in ("Eye", "EyeHappy", "EyeX"):
        m = bpy.data.materials.get(name)
        if m:
            m.surface_render_method = "BLENDED"
            m.node_tree.nodes["Principled BSDF"].inputs["Alpha"].default_value = 1.0 if name == eyes else 0.0
    scene.frame_set(frame)
    if scene.camera and view != scene.get("view", "front"):
        cam = scene.camera
        if view == "back":
            cam.location = (-1.0, 2.7, 1.3)
            cam.rotation_euler = Euler((math.radians(78), 0, math.radians(200)))
        elif view == "close":
            cam.location = (0.55, -1.5, 1.0)
            cam.rotation_euler = Euler((math.radians(80), 0, math.radians(20)))
        else:
            cam.location = (1.0, -2.7, 1.25)
            cam.rotation_euler = Euler((math.radians(78), 0, math.radians(20)))
        scene["view"] = view
    if not scene.camera:
        cam = bpy.data.objects.new("Cam", bpy.data.cameras.new("Cam"))
        scene.collection.objects.link(cam)
        cam.location = (0.9, -2.4, 1.05)
        cam.rotation_euler = Euler((math.radians(78), 0, math.radians(20)))
        cam.data.lens = 50
        scene.camera = cam
        sun = bpy.data.objects.new("Sun", bpy.data.lights.new("Sun", "SUN"))
        sun.data.energy = 4
        sun.rotation_euler = Euler((math.radians(50), math.radians(10), math.radians(30)))
        scene.collection.objects.link(sun)
        world = bpy.data.worlds.new("W")
        world.use_nodes = True
        world.node_tree.nodes["Background"].inputs[0].default_value = (0.35, 0.28, 0.3, 1)
        world.node_tree.nodes["Background"].inputs[1].default_value = 0.8
        scene.world = world
    engines = [e.identifier for e in bpy.types.RenderSettings.bl_rna.properties["engine"].enum_items]
    scene.render.engine = "BLENDER_EEVEE_NEXT" if "BLENDER_EEVEE_NEXT" in engines else ("BLENDER_EEVEE" if "BLENDER_EEVEE" in engines else "BLENDER_WORKBENCH")
    scene.render.resolution_x = 480
    scene.render.resolution_y = 560
    scene.render.film_transparent = False
    scene.render.filepath = os.path.join(PREVIEW_DIR, f"{char_id}_{suffix}.png")
