def reset_scene():
    bpy.ops.wm.read_factory_settings(use_empty=True)
    scene = bpy.context.scene
    scene.render.fps = FPS
    return scene


def material(name, color, roughness=0.45, metallic=0.0, emission=None, emission_strength=0.0, coat=0.0, alpha=1.0):
    mat = bpy.data.materials.get(name) or bpy.data.materials.new(name)
    mat.use_nodes = True
    bsdf = mat.node_tree.nodes.get("Principled BSDF")
    bsdf.inputs["Base Color"].default_value = (*color, 1.0)
    bsdf.inputs["Roughness"].default_value = roughness
    bsdf.inputs["Metallic"].default_value = metallic
    if "Coat Weight" in bsdf.inputs:
        bsdf.inputs["Coat Weight"].default_value = coat
    if emission is not None:
        bsdf.inputs["Emission Color"].default_value = (*emission, 1.0)
        bsdf.inputs["Emission Strength"].default_value = emission_strength
    if alpha < 1.0:
        bsdf.inputs["Alpha"].default_value = alpha
        mat.surface_render_method = "BLENDED" if hasattr(mat, "surface_render_method") else mat.blend_method
    mat.diffuse_color = (*color, 1.0)  # viewport / workbench color
    return mat


def srgb(hexstr):
    """Hex sRGB → linear RGB tuple (Blender colors are linear)."""
    h = hexstr.lstrip("#")
    c = [int(h[i : i + 2], 16) / 255 for i in (0, 2, 4)]
    return tuple(v / 12.92 if v <= 0.04045 else ((v + 0.055) / 1.055) ** 2.4 for v in c)


def activate(obj):
    bpy.ops.object.select_all(action="DESELECT")
    obj.select_set(True)
    bpy.context.view_layer.objects.active = obj


def apply_modifiers(obj):
    activate(obj)
    for m in list(obj.modifiers):
        bpy.ops.object.modifier_apply(modifier=m.name)


def smooth(obj, subdiv=0):
    if subdiv:
        mod = obj.modifiers.new("Subsurf", "SUBSURF")
        mod.levels = subdiv
        mod.render_levels = subdiv
        apply_modifiers(obj)
    for p in obj.data.polygons:
        p.use_smooth = True


def assign(obj, mat):
    obj.data.materials.clear()
    obj.data.materials.append(mat)


def uv_sphere(name, radius, loc, scale=(1, 1, 1), mat=None, segments=32, rings=16, rot=(0, 0, 0)):
    bpy.ops.mesh.primitive_uv_sphere_add(segments=segments, ring_count=rings, radius=radius, location=loc, rotation=rot)
    o = bpy.context.active_object
    o.name = name
    o.scale = scale
    bpy.ops.object.transform_apply(location=False, rotation=True, scale=True)
    smooth(o)
    if mat:
        assign(o, mat)
    return o


def cylinder(name, r1, r2, depth, loc, mat=None, verts=24, rot=(0, 0, 0), subdiv=0, bevel=0.0):
    bpy.ops.mesh.primitive_cone_add(vertices=verts, radius1=r1, radius2=r2, depth=depth, location=loc, rotation=rot)
    o = bpy.context.active_object
    o.name = name
    if bevel:
        b = o.modifiers.new("Bevel", "BEVEL")
        b.width = bevel
        b.segments = 3
        apply_modifiers(o)
    smooth(o, subdiv)
    if mat:
        assign(o, mat)
    return o


def torus(name, major, minor, loc, mat=None, rot=(0, 0, 0), scale=(1, 1, 1)):
    bpy.ops.mesh.primitive_torus_add(major_radius=major, minor_radius=minor, location=loc, rotation=rot, major_segments=40, minor_segments=12)
    o = bpy.context.active_object
    o.name = name
    o.scale = scale
    bpy.ops.object.transform_apply(location=False, rotation=True, scale=True)
    smooth(o)
    if mat:
        assign(o, mat)
    return o


def tube(name, points, radius, mat, resolution=12):
    """A bevelled curve (fuses, scarf tails) converted to mesh."""
    curve = bpy.data.curves.new(name, "CURVE")
    curve.dimensions = "3D"
    curve.bevel_depth = radius
    curve.bevel_resolution = 4
    curve.resolution_u = resolution
    spline = curve.splines.new("BEZIER")
    spline.bezier_points.add(len(points) - 1)
    for bp, p in zip(spline.bezier_points, points):
        bp.co = p
        bp.handle_left_type = bp.handle_right_type = "AUTO"
    o = bpy.data.objects.new(name, curve)
    bpy.context.collection.objects.link(o)
    activate(o)
    bpy.ops.object.convert(target="MESH")
    o = bpy.context.active_object
    smooth(o)
    assign(o, mat)
    return o


def skin_body(name, verts, edges, radii, root, mat):
    """Organic body: vertex skeleton → Skin modifier → subdivision."""
    mesh = bpy.data.meshes.new(name)
    mesh.from_pydata(verts, edges, [])
    o = bpy.data.objects.new(name, mesh)
    bpy.context.collection.objects.link(o)
    activate(o)
    skin = o.modifiers.new("Skin", "SKIN")
    skin.use_smooth_shade = True
    sv = mesh.skin_vertices[0].data
    for i, r in enumerate(radii):
        sv[i].radius = r
    sv[root].use_root = True
    sub = o.modifiers.new("Subsurf", "SUBSURF")
    sub.levels = 2
    apply_modifiers(o)
    smooth(o)
    assign(o, mat)
    return o


def rounded_box(name, half, loc, mat, bevel=0.1, subdiv=2, taper=0.0):
    """Soft "marshmallow" block: bevelled cube + subdivision. `taper` narrows the bottom."""
    bpy.ops.mesh.primitive_cube_add(size=2, location=loc)
    o = bpy.context.active_object
    o.name = name
    o.scale = half
    bpy.ops.object.transform_apply(location=False, rotation=False, scale=True)
    b = o.modifiers.new("Bevel", "BEVEL")
    b.width = bevel
    b.segments = 4
    b.limit_method = "NONE"
    apply_modifiers(o)
    smooth(o, subdiv)
    if taper:
        hh = half[2]
        for v in o.data.vertices:
            f = 1 - taper * min(1.0, max(0.0, (hh - v.co.z) / (2 * hh)))
            v.co.x *= f
            v.co.y *= f
    assign(o, mat)
    return o


def shell_slice(name, half, loc, mat, keep, thickness=0.012, bevel=0.1, taper=0.0):
    """A slice of a rounded box slightly larger than the head (headbands, masks)."""
    o = rounded_box(name, half, loc, mat, bevel=bevel, taper=taper)
    bm = bmesh.new()
    bm.from_mesh(o.data)
    bmesh.ops.delete(bm, geom=[v for v in bm.verts if not keep(v.co)], context="VERTS")
    bm.to_mesh(o.data)
    bm.free()
    mod = o.modifiers.new("Solid", "SOLIDIFY")
    mod.thickness = thickness
    apply_modifiers(o)
    return o


def face_decal(name, target, mat, cx, cz, w, h, n=2.6, angle=0.0, bend=0.0, thickness=0.014):
    """Flat rounded-rectangle shape wrapped onto the head surface (eyes, expressions).

    A grid is mapped square -> disc -> superellipse, optionally rotated and bent into an arc,
    placed in front of the face, projected onto `target` and given thickness outward."""
    bpy.ops.mesh.primitive_grid_add(x_subdivisions=12, y_subdivisions=24, size=2, location=(0, 0, 0))
    o = bpy.context.active_object
    o.name = name
    ca, sa = math.cos(angle), math.sin(angle)
    for v in o.data.vertices:
        u, vv = v.co.x, v.co.y
        x = u * math.sqrt(max(0.0, 1 - vv * vv / 2))
        y = vv * math.sqrt(max(0.0, 1 - u * u / 2))
        th = math.atan2(y, x)
        r = (abs(math.cos(th)) ** n + abs(math.sin(th)) ** n) ** (-1 / n)
        x, y = x * r * w / 2, y * r * h / 2
        x, y = x * ca - y * sa, x * sa + y * ca
        y -= bend * x * x
        v.co = (cx + x, -0.6, cz + y)  # in front of the face; normal faces -Y
    sw = o.modifiers.new("Wrap", "SHRINKWRAP")
    sw.target = target
    sw.wrap_method = "PROJECT"
    sw.use_project_y = True
    sw.use_negative_direction = True
    sw.use_positive_direction = True
    sw.offset = 0.002
    sol = o.modifiers.new("Solid", "SOLIDIFY")
    sol.thickness = thickness
    sol.offset = 1.0
    apply_modifiers(o)
    smooth(o)
    assign(o, mat)
    return o


