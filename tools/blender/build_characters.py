    parts["head"].append(shell_slice("Mask", (hw + 0.01, hd + 0.01, hh + 0.01), (0, 0, hz), mats["Cloth"], lambda c: c.z < -0.155 and c.y < 0.05, thickness=0.012, bevel=HEAD_BEVEL, taper=HEAD_TAPER))
    # Scarf around the neck.
